
#  Escape Back space = \b
print ("Hello\bWorld") # will remove o

print ("Hello Py\bthon") # will remove y

# newline = \
print ("Hello \
I love \
Python")

# Escape Back Slash = \\
print ("I Love Back Slash \\") 

# Escape Single Quote \'
print ("I Love Single Quote \'Test\' ")

# Escape Double Quotes = \"
print ("I Love Double Quotes \"success\" ")

# Line Feed & New Line
print ("Once Line\nHello World\nSecond Line\nHello Python")


# Carriage Return = \r
print ("123456\rABCDEF")

# Horizontal Tab = \t
print ("Hello\tPython")

# Character Hex Value = \xhh

print("\x4F\x73")